create or replace function public.is_valid_menu_option_groups(value jsonb)
returns boolean
language sql
immutable
set search_path = public
as $$
  select jsonb_typeof(value) = 'array'
    and not exists (
      select 1
      from jsonb_array_elements(value) as groups(group_item)
      where jsonb_typeof(group_item) is distinct from 'object'
         or jsonb_typeof(group_item -> 'id') is distinct from 'string'
         or btrim(group_item ->> 'id') = ''
         or jsonb_typeof(group_item -> 'name') is distinct from 'string'
         or btrim(group_item ->> 'name') = ''
         or jsonb_typeof(group_item -> 'type') is distinct from 'string'
         or group_item ->> 'type' not in ('single', 'multiple')
         or (
           group_item ? 'required'
           and jsonb_typeof(group_item -> 'required') is distinct from 'boolean'
         )
         or jsonb_typeof(group_item -> 'options') is distinct from 'array'
         or jsonb_array_length(group_item -> 'options') = 0
         or exists (
          select 1
          from jsonb_array_elements(group_item -> 'options') as options(option_item)
          where jsonb_typeof(option_item) is distinct from 'object'
             or jsonb_typeof(option_item -> 'id') is distinct from 'string'
             or btrim(option_item ->> 'id') = ''
             or jsonb_typeof(option_item -> 'name') is distinct from 'string'
             or btrim(option_item ->> 'name') = ''
             or jsonb_typeof(option_item -> 'priceDelta') is distinct from 'number'
         )
    );
$$;

