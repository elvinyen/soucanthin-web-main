create or replace function public.process_wallet_payment(
  user_id_input uuid,
  order_id_input uuid,
  amount_input numeric
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_balance numeric(10, 2);
begin
  select balance
  into current_balance
  from public.wallets
  where user_id = user_id_input
  for update;

